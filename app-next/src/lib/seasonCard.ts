import type { SeasonPalette, UserProfile } from '../types';

/**
 * The card she actually posts.
 *
 * The old one drew "Certificate ID: DQxy…hQ7w" and "YOUR PALETTE SEASONAL CERTIFICATION"
 * in the browser's default serif, and then downloaded it. Three separate problems in one
 * object:
 *
 *   It looked like a diploma. Nobody posts a diploma. The thing she will actually put on
 *   her story is a beautiful colour object with her season on it, and the more it looks
 *   like a certificate the less it travels.
 *
 *   It printed her seal code. That is the address of her palette account. Putting it on an
 *   image designed to be posted publicly, on a card generated by the app that promises her
 *   nothing about her is public, is the worst kind of leak: one we built and shipped
 *   ourselves. It is gone, and it is not coming back for design reasons.
 *
 *   It only downloaded. A file in her downloads folder is not a share. On a phone, the
 *   share sheet takes the image straight into whatever app she is going to post it in, and
 *   that is one tap instead of six.
 *
 * Drawn at 1080x1350, which is the four-to-five crop Instagram gives the most room to and
 * which survives being cropped square or stretched to a story without losing the season
 * name or the swatches.
 */

export const CARD_W = 1080;
export const CARD_H = 1350;

const INK = '#43203B';
const BLUSH = '#FBF3EE';
const PAPER = '#FFFBF7';
const MAUVE = '#C9799B';
const MAUVE_DEEP = '#A85578';
const MUTED = '#8A6580';

/* Fraunces and Karla are already loaded for the app. Canvas will silently fall back to a
   system face if they are not ready yet, and the card is the one place that fallback is
   very visible, so it waits. */
async function fontsReady(): Promise<void> {
  try {
    await document.fonts.ready;
    await Promise.all([
      document.fonts.load('300 96px Fraunces'),
      document.fonts.load('600 34px Karla'),
      document.fonts.load('italic 400 120px Fraunces'),
    ]);
  } catch {
    /* A card in the wrong font beats no card. */
  }
}

function roundRect(ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number, r: number) {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
}

/* A dish, the same object the app draws everywhere: pigment pressed into a well, lit from
   above left. Flat circles would look like a colour picker. */
function dish(ctx: CanvasRenderingContext2D, cx: number, cy: number, r: number, hex: string) {
  ctx.save();
  ctx.beginPath();
  ctx.arc(cx, cy + 6, r, 0, Math.PI * 2);
  ctx.fillStyle = 'rgba(67,32,59,0.16)';
  ctx.filter = 'blur(10px)';
  ctx.fill();
  ctx.restore();

  ctx.beginPath();
  ctx.arc(cx, cy, r, 0, Math.PI * 2);
  ctx.fillStyle = hex;
  ctx.fill();

  const sheen = ctx.createRadialGradient(cx - r * 0.35, cy - r * 0.4, r * 0.05, cx, cy, r);
  sheen.addColorStop(0, 'rgba(255,251,247,0.42)');
  sheen.addColorStop(0.55, 'rgba(255,251,247,0.05)');
  sheen.addColorStop(1, 'rgba(27,17,32,0.22)');
  ctx.fillStyle = sheen;
  ctx.fill();

  ctx.lineWidth = 3;
  ctx.strokeStyle = 'rgba(255,251,247,0.75)';
  ctx.stroke();
}

export interface CardInput {
  profile: UserProfile;
  season: SeasonPalette;
  /* Where the card sends whoever sees it. */
  link: string;
}

export async function renderSeasonCard({ profile, season, link }: CardInput): Promise<HTMLCanvasElement> {
  await fontsReady();

  const c = document.createElement('canvas');
  c.width = CARD_W;
  c.height = CARD_H;
  const ctx = c.getContext('2d');
  if (!ctx) throw new Error('no canvas');

  /* Ground: blush, with the deep brown velvet along the bottom that the app itself uses,
     so a card seen on its own still reads as Oira. */
  ctx.fillStyle = BLUSH;
  ctx.fillRect(0, 0, CARD_W, CARD_H);

  const glow = ctx.createRadialGradient(CARD_W, 0, 40, CARD_W, 0, 720);
  glow.addColorStop(0, 'rgba(201,121,155,0.55)');
  glow.addColorStop(0.5, 'rgba(231,166,192,0.22)');
  glow.addColorStop(1, 'rgba(243,221,214,0)');
  ctx.fillStyle = glow;
  ctx.fillRect(0, 0, CARD_W, 780);

  const velvet = ctx.createLinearGradient(0, CARD_H - 260, CARD_W, CARD_H);
  velvet.addColorStop(0, '#2A160F');
  velvet.addColorStop(0.45, '#4A2B1C');
  velvet.addColorStop(0.8, '#6E4128');
  velvet.addColorStop(1, '#A85578');
  ctx.save();
  ctx.beginPath();
  ctx.moveTo(0, CARD_H);
  ctx.lineTo(0, CARD_H - 150);
  ctx.quadraticCurveTo(CARD_W * 0.4, CARD_H - 300, CARD_W, CARD_H - 210);
  ctx.lineTo(CARD_W, CARD_H);
  ctx.closePath();
  ctx.fillStyle = velvet;
  ctx.fill();
  ctx.restore();

  /* The card itself. */
  const CX = 72, CY = 150, CW = CARD_W - 144, CH = 900;
  ctx.save();
  ctx.shadowColor = 'rgba(67,32,59,0.22)';
  ctx.shadowBlur = 48;
  ctx.shadowOffsetY = 22;
  roundRect(ctx, CX, CY, CW, CH, 56);
  ctx.fillStyle = PAPER;
  ctx.fill();
  ctx.restore();

  ctx.textAlign = 'left';
  ctx.fillStyle = MAUVE_DEEP;
  ctx.font = '700 26px Karla, sans-serif';
  ctx.letterSpacing = '6px';
  ctx.fillText('MY SEASON', CX + 72, CY + 118);
  ctx.letterSpacing = '0px';

  /* Her season, as big as it will go. This is the whole point of the object. */
  ctx.fillStyle = INK;
  const words = season.name.split(' ');
  ctx.font = '300 108px Fraunces, Georgia, serif';
  let y = CY + 250;
  for (const w of words) {
    ctx.fillText(w, CX + 68, y);
    y += 112;
  }

  ctx.fillStyle = MUTED;
  ctx.font = '400 34px Karla, sans-serif';
  ctx.fillText(`${season.undertone} undertone, ${season.depth.toLowerCase()} depth`, CX + 72, y + 12);

  /* Her six, as dishes. */
  const shown = season.swatches.slice(0, 6);
  const r = 62;
  const gap = (CW - 144 - r * 2) / Math.max(1, shown.length - 1);
  shown.forEach((sw, i) => {
    dish(ctx, CX + 72 + r + gap * i, y + 150, r, sw.hex);
  });

  ctx.fillStyle = MUTED;
  ctx.font = '400 30px Karla, sans-serif';
  ctx.fillText(`Best in ${season.bestMetals.slice(0, 2).join(' and ').toLowerCase()}`, CX + 72, y + 280);

  /* Her name if she picked one. Never the seal code. */
  if (profile.name) {
    ctx.fillStyle = MAUVE;
    ctx.font = 'italic 400 40px Fraunces, Georgia, serif';
    ctx.fillText(profile.name, CX + 72, y + 348);
  }

  /* The invitation, on the velvet, where the eye finishes. */
  ctx.textAlign = 'center';
  ctx.fillStyle = '#FFFBF7';
  ctx.font = '300 52px Fraunces, Georgia, serif';
  ctx.fillText('Find your season.', CARD_W / 2, CARD_H - 132);

  ctx.fillStyle = 'rgba(255,251,247,0.72)';
  ctx.font = '400 28px Karla, sans-serif';
  ctx.fillText(link.replace(/^https?:\/\//, ''), CARD_W / 2, CARD_H - 78);

  ctx.fillStyle = 'rgba(255,251,247,0.5)';
  ctx.font = '400 24px Karla, sans-serif';
  ctx.fillText('read on your phone, kept there', CARD_W / 2, CARD_H - 38);

  return c;
}

export function canvasToFile(c: HTMLCanvasElement, name: string): Promise<File> {
  return new Promise((resolve, reject) => {
    c.toBlob((blob) => {
      if (!blob) return reject(new Error('no blob'));
      resolve(new File([blob], name, { type: 'image/png' }));
    }, 'image/png');
  });
}

/* The link she hands out.
 *
 * `r` is the referral hook. There is no points system behind it yet and this file is not
 * pretending otherwise; the parameter is here so that when there is one, every card already
 * in circulation is already carrying it. Adding it later would mean every card shared before
 * that day credits nobody. */
export function shareLink(profile: UserProfile): string {
  const base = typeof window !== 'undefined' ? window.location.origin : 'https://myoira.com';
  const handle = profile.name?.trim();
  return handle ? `${base}/?r=${encodeURIComponent(handle)}` : base;
}
