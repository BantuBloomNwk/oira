#!/usr/bin/env python3
"""Pull Fraunces and Karla out of Google Fonts and into our own origin.

Writes the woff2 files to public/fonts and an @font-face sheet to src/fonts.css. Keeps the
latin and latin-ext subsets and drops cyrillic, greek and vietnamese, which are bytes on
the wire for glyphs nothing in this app renders.
"""
import hashlib
import pathlib
import re
import urllib.request

SPEC = (
    "https://fonts.googleapis.com/css2"
    "?family=Fraunces:ital,opsz,wght@0,9..144,300;0,9..144,400;0,9..144,500;0,9..144,600;"
    "1,9..144,300;1,9..144,400;1,9..144,500"
    "&family=Karla:wght@300;400;500;600;700&display=swap"
)
# Google serves a different stylesheet per browser. Without a real UA it hands back the
# ancient ttf sheet instead of woff2.
UA = {"User-Agent": "Mozilla/5.0 (X11; Linux x86_64; rv:128.0) Gecko/20100101 Firefox/128.0"}
KEEP = ("latin", "latin-ext")

HEADER = """/* Fraunces and Karla, served from our own origin.
 *
 * They came from fonts.googleapis.com, which on a privacy app is the wrong place for them:
 * every single page view told Google that this woman opened Oira, from which IP, with
 * which browser, before she had agreed to anything. That is a promise the rest of the app
 * keeps and the type was quietly breaking.
 *
 * It is also faster. Two fewer origins means two fewer DNS lookups and TLS handshakes on
 * the critical path, and the files now arrive multiplexed over the same HTTP/2 connection
 * as everything else. Nothing was lost: same families, same weights, latin and latin-ext
 * subsets only.
 *
 * Generated by scripts/fetch-fonts.py. Do not hand edit.
 */
"""


def main() -> None:
    css = urllib.request.urlopen(
        urllib.request.Request(SPEC, headers=UA), timeout=60
    ).read().decode()

    out = pathlib.Path("public/fonts")
    out.mkdir(parents=True, exist_ok=True)

    faces = []
    for subset, block in re.findall(r"/\*\s*([a-z0-9-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})", css):
        if subset not in KEEP:
            continue
        url = re.search(r"url\((https://fonts\.gstatic\.com[^)]+)\)", block).group(1)
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1).lower().replace(" ", "-")
        style = "italic" if "font-style: italic" in block else "normal"
        name = f"{family}-{subset}-{style}-{hashlib.sha1(url.encode()).hexdigest()[:6]}.woff2"
        (out / name).write_bytes(
            urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60).read()
        )
        faces.append(block.replace(url, f"/fonts/{name}"))

    pathlib.Path("src/fonts.css").write_text(HEADER + "\n" + "\n\n".join(faces) + "\n")
    print(f"wrote {len(faces)} faces and {len(set(out.iterdir()))} files")


if __name__ == "__main__":
    main()
